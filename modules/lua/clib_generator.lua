-- Normalize function descriptors and prepare C declarations
local function _prepare_context(config)
    local prefix = config.prefix or "mylib_"
    local prefix_upper = prefix:upper()
    local api_macro = config.api_macro or (prefix_upper .. "API")
    local mode = config.mode or "context"
    local entry_mod = config.entry_module or "init"
    local preload_fn = config.preload_function or (prefix .. "preload_bundled_modules")
    local header_guard = config.header_guard or (prefix_upper .. "H")
    local header_name = path.filename(config.header_file or (prefix .. ".h"))

    local raw_libs = config.lua_libs
    local raw_exclude = config.lua_libs_exclude
    local resolved_libs = nil

    if raw_libs or raw_exclude then
        local CANONICAL_LUA_LIBS = {
            "base", "package", "coroutine", "table", "io", "os", "string", "math", "utf8", "debug"
        }
        local STD_LUA_LIBS = {
            ["_G"]        = {name = "_G",        openf = "luaopen_base"},
            ["base"]      = {name = "_G",        openf = "luaopen_base"},
            ["coroutine"] = {name = "coroutine", openf = "luaopen_coroutine"},
            ["table"]     = {name = "table",     openf = "luaopen_table"},
            ["io"]        = {name = "io",        openf = "luaopen_io"},
            ["os"]        = {name = "os",        openf = "luaopen_os"},
            ["string"]    = {name = "string",    openf = "luaopen_string"},
            ["math"]      = {name = "math",      openf = "luaopen_math"},
            ["utf8"]      = {name = "utf8",      openf = "luaopen_utf8"},
            ["debug"]     = {name = "debug",     openf = "luaopen_debug"},
            ["package"]   = {name = "package",   openf = "luaopen_package"}
        }
        local exclude_set = {}
        if raw_exclude then
            for _, ex in ipairs(table.wrap(raw_exclude)) do
                exclude_set[ex] = true
            end
        end

        local base_list = raw_libs and table.wrap(raw_libs) or CANONICAL_LUA_LIBS
        resolved_libs = {}
        for _, libname in ipairs(base_list) do
            if not exclude_set[libname] then
                local item = STD_LUA_LIBS[libname] or {name = libname, openf = "luaopen_" .. libname}
                table.insert(resolved_libs, item)
            end
        end
    end

    local normalized_exports = {}
    for _, fn in ipairs(config.exports or {}) do
        local c_name = fn.c_name or (prefix .. fn.name)
        local stateless_c_name = fn.stateless_c_name
        if not stateless_c_name then
            if mode == "both" then
                stateless_c_name = c_name .. "_oneshot"
            else
                stateless_c_name = c_name
            end
        end

        local c_params = {}
        local c_args = {}

        -- Input parameters
        for _, p in ipairs(fn.params or {}) do
            if p.type == "string" then
                table.insert(c_params, "const char *" .. p.name)
                table.insert(c_args, p.name)
            elseif p.type == "bytes" or p.type == "buffer" then
                table.insert(c_params, "const void *" .. p.name)
                table.insert(c_params, "size_t " .. p.name .. "_len")
                table.insert(c_args, p.name)
                table.insert(c_args, p.name .. "_len")
            elseif p.type == "int" then
                table.insert(c_params, "int " .. p.name)
                table.insert(c_args, p.name)
            elseif p.type == "int64" then
                table.insert(c_params, "int64_t " .. p.name)
                table.insert(c_args, p.name)
            elseif p.type == "double" or p.type == "number" then
                table.insert(c_params, "double " .. p.name)
                table.insert(c_args, p.name)
            elseif p.type == "bool" or p.type == "boolean" then
                table.insert(c_params, "int " .. p.name)
                table.insert(c_args, p.name)
            end
        end

        -- Output parameters (return values)
        for _, r in ipairs(fn.returns or {}) do
            local rname = r.name or "result"
            if r.type == "string" then
                table.insert(c_params, "char **out_" .. rname)
                table.insert(c_args, "out_" .. rname)
            elseif r.type == "bytes" or r.type == "buffer" then
                table.insert(c_params, "char **out_" .. rname)
                table.insert(c_params, "size_t *out_" .. rname .. "_len")
                table.insert(c_args, "out_" .. rname)
                table.insert(c_args, "out_" .. rname .. "_len")
            elseif r.type == "int" then
                table.insert(c_params, "int *out_" .. rname)
                table.insert(c_args, "out_" .. rname)
            elseif r.type == "int64" then
                table.insert(c_params, "int64_t *out_" .. rname)
                table.insert(c_args, "out_" .. rname)
            elseif r.type == "double" or r.type == "number" then
                table.insert(c_params, "double *out_" .. rname)
                table.insert(c_args, "out_" .. rname)
            elseif r.type == "bool" or r.type == "boolean" then
                table.insert(c_params, "int *out_" .. rname)
                table.insert(c_args, "out_" .. rname)
            end
        end

        -- Standard error message parameter
        table.insert(c_params, "char **err_msg")
        table.insert(c_args, "err_msg")

        table.insert(normalized_exports, {
            name = fn.name,
            c_name = c_name,
            stateless_c_name = stateless_c_name,
            desc = fn.desc,
            params = fn.params or {},
            returns = fn.returns or {},
            c_params_decl = table.concat(c_params, ",\n    "),
            c_args_pass = table.concat(c_args, ",\n        ")
        })
    end

    return {
        prefix = prefix,
        prefix_upper = prefix_upper,
        api_macro = api_macro,
        mode = mode,
        entry_module = entry_mod,
        preload_function = preload_fn,
        lua_libs = resolved_libs,
        header_extra = config.header_extra,
        header_guard = header_guard,
        header_name = header_name,
        exports = normalized_exports
    }
end

-- Generate C public header source
function generate_header(config)
    local ctx = _prepare_context(config)
    return template.render(HEADER_TEMPLATE, ctx)
end

-- Generate C bridge implementation source
function generate_bridge(config)
    local ctx = _prepare_context(config)
    return template.render(BRIDGE_TEMPLATE, ctx)
end
