function main(T)
    local tests = {}

    table.insert(tests, {
        name = "nelua rule files exist and define expected rule names and extensions",
        func = function ()
            local content_xmake = io.readfile(path.join(os.projectdir(), "rules/lang/nelua/xmake.lua"))
            T.assert_not_nil(content_xmake)
            T.assert_true(content_xmake:find('rule%("recudo%.lang%.nelua"%)') ~= nil)
            T.assert_true(content_xmake:find('set_extensions%("%.nelua"%)') ~= nil)
        end
    })

    table.insert(tests, {
        name = "nelua compiler generates both C and Lua code",
        func = function ()
            local xmake_pkg_nelua = path.join(os.getenv("HOME") or "", ".xmake/packages/n/nelua")
            local nelua_bin
            if os.isdir(xmake_pkg_nelua) then
                local matches = os.files(path.join(xmake_pkg_nelua, "**/bin/nelua*"))
                for _, match in ipairs(matches or {}) do
                    local fn = path.filename(match)
                    if fn == "nelua" or fn == "nelua.bat" then
                        nelua_bin = match
                        break
                    end
                end
            end
            if not nelua_bin or not os.isexec(nelua_bin) then
                import("lib.detect.find_tool")
                local tool = find_tool("nelua")
                nelua_bin = tool and tool.program
            end

            if not nelua_bin or not os.isexec(nelua_bin) then
                return
            end

            local tmpdir = path.join(os.tmpdir(), "recudo_test_nelua")
            os.mkdir(tmpdir)

            local test_nelua = path.join(tmpdir, "test.nelua")
            local out_c = path.join(tmpdir, "test.c")
            local out_lua = path.join(tmpdir, "test.lua")

            io.writefile(test_nelua, [[
                local function square(x: integer): integer
                    return x * x
                end
                print(square(9))
            ]])

            -- 1. Transpile to C
            local ok_c = try {
                function ()
                    os.vrunv(nelua_bin, {"-c", test_nelua, "-o", out_c})
                    return true
                end
            }
            T.assert_true(ok_c == true, "nelua -c should succeed")
            T.assert_true(os.isfile(out_c), "generated C file should exist")
            local c_code = io.readfile(out_c)
            T.assert_true(c_code:find("Generated by Nelua", 1, true) ~= nil)
            T.assert_true(c_code:find("nelua_main", 1, true) ~= nil)

            -- 2. Transpile to Lua
            local ok_lua = try {
                function ()
                    os.vrunv(nelua_bin, {"-g", "lua", "-c", test_nelua, "-o", out_lua})
                    return true
                end
            }
            T.assert_true(ok_lua == true, "nelua -g lua should succeed")
            T.assert_true(os.isfile(out_lua), "generated Lua file should exist")
            local lua_code = io.readfile(out_lua)
            T.assert_true(lua_code:find("square", 1, true) ~= nil)

            -- Cleanup
            os.rm(tmpdir)
        end
    })

    return tests
end
